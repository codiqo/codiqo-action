# frozen_string_literal: true

#
# Writes gitlab/codiqo.yml from action.yml, so the GitLab template takes exactly the action's inputs, with
# the action's defaults and descriptions, and cannot drift from it. Run it after any change to action.yml's
# inputs; CI fails when the committed template differs from what this produces.
#
#   ruby gitlab/generate.rb > gitlab/codiqo.yml
#
# Each input becomes a spec:inputs entry and a job variable named as action.yml names it for the scripts
# (max-commits-per-run reaches them as CODIQO_IN_MAX_COMMITS); an input that only decides whether a step
# runs, which action.yml passes to no script, becomes CODIQO_IN_<NAME>. Every string is written as a JSON
# string, which is also a valid YAML double-quoted scalar, so no description or default needs escaping.
#

require 'json'
require 'yaml'

ROOT = File.expand_path('..', __dir__)
ACTION = File.read(File.join(ROOT, 'action.yml'))

#
# Inputs with no place in a GitLab job. The API key and settings.xml are secrets, which a GitLab project
# keeps as masked CI/CD variables (CODIQO_API_KEY, CODIQO_IN_SETTINGS_XML) rather than in its committed
# configuration. The JDK and its cache are the job image's business, the log artifact is the job's own,
# and the deprecated names were never part of the GitLab template.
#
EXCLUDED = %w[
  api-key settings-xml java-version java-distribution cache upload-logs log-artifact-name log-retention-days
  test-failure-halt-share test-failure-halt-min-tests
].freeze

#
# Inputs of the GitLab job itself, ahead of the action's.
#
GITLAB_INPUTS = [
  ['stage', 'test', 'Pipeline stage the codiqo-analyze job runs in.'],
  ['image', 'eclipse-temurin:25-jdk',
   'Job image. It needs a JDK and bash; git, python3, curl, tar and gzip are installed when missing and the job ' \
   'runs as root, and Node.js for the review when it has no npm. Choose the JDK the project builds with: every ' \
   'analysed commit is built with it. The language server, which needs Java 25 or newer, runs on that JDK when it ' \
   'is jdtls-java-version or newer, and otherwise on a Temurin build the job downloads beside it.'],
  ['job-timeout', '6h',
   'GitLab timeout of the whole job, which works through every pending commit in turn. It can exceed the ' \
   'project timeout but not the runner\'s.'],
  ['action-ref', 'main',
   'Ref of codiqo/codiqo-action whose scripts the job downloads. Keep it the same as the ref in the include URL.'],
  ['action-archive-url', '',
   'Where the job downloads the action\'s scripts from, as a .tar.gz with one top directory. Empty uses ' \
   'codiqo/codiqo-action at action-ref on GitHub; set it for a runner that reaches GitHub only through a mirror.'],
  ['node-version', '24.22.1',
   'Node.js release installed, SHA-256 checked, for the npm that installs OpenCode when the image has no npm. ' \
   'Only with review: true.'],
  ['log-retention-days', '7', 'Days the job keeps its log artifact.']
].freeze

def env_names
  names = Hash.new { |hash, key| hash[key] = [] }
  ACTION.scan(/^\s+(CODIQO_[A-Z0-9_]+): \$\{\{ inputs\.([a-z0-9-]+) \}\}$/) do |env, input|
    names[input] << env unless names[input].include?(env)
  end
  names
end

def quoted(value)
  JSON.generate(value.to_s)
end

action = YAML.safe_load(ACTION)
mapped = env_names
inputs = action.fetch('inputs').reject { |name, _| EXCLUDED.include?(name) }

out = []
out << '# Codiqo for GitLab CI: indexes the project\'s history, then analyses and submits every commit that still'
out << '# lacks an analysis, one at a time, as codiqo/codiqo-action does on GitHub.'
out << '#'
out << '# GENERATED from action.yml by gitlab/generate.rb. Edit those and regenerate; do not edit this file.'
out << '#'
out << '#   include:'
out << '#     - remote: https://raw.githubusercontent.com/codiqo/codiqo-action/main/gitlab/codiqo.yml'
out << '#       inputs:'
out << '#         action-ref: main'
out << '#'
out << '# The API key is a masked CI/CD variable named CODIQO_API_KEY, never an input. Any input below can also be'
out << '# set as a CI/CD variable under its job variable name (CODIQO_IN_...), which wins over the input.'
out << 'spec:'
out << '  inputs:'
GITLAB_INPUTS.each do |name, default, description|
  out << "    #{name}:"
  out << "      description: #{quoted(description)}"
  out << "      default: #{quoted(default)}"
end
inputs.each do |name, spec|
  out << "    #{name}:"
  out << "      description: #{quoted(spec.fetch('description', ''))}"
  out << "      default: #{quoted(spec.fetch('default', ''))}"
end
out << '---'
out << 'codiqo-analyze:'
out << '  stage: $[[ inputs.stage ]]'
out << '  image: $[[ inputs.image ]]'
out << '  timeout: $[[ inputs.job-timeout ]]'
out << '  # one analysis at a time per project, as the action\'s concurrency group does: two would review'
out << '  # and submit the same pending commits'
out << '  resource_group: codiqo-analyze'
out << '  interruptible: false'
out << '  rules:'
out << '    - if: $CI_PIPELINE_SOURCE == "merge_request_event"'
out << '      when: never'
out << '    - if: $CI_COMMIT_TAG'
out << '      when: never'
out << '    - if: $CI_PIPELINE_SOURCE =~ /^(schedule|web|api|trigger|pipeline)$/'
out << '    - if: $CI_PIPELINE_SOURCE == "push" && $CI_COMMIT_BRANCH == $CI_DEFAULT_BRANCH'
out << '  variables:'
out << '    # every commit, not the 20 GitLab fetches by default: a commit whose parent is missing is not analysed'
out << '    GIT_DEPTH: "0"'
out << '    GIT_STRATEGY: clone'
out << '    CODIQO_ACTION_REF: $[[ inputs.action-ref ]]'
out << '    CODIQO_ACTION_ARCHIVE_URL: $[[ inputs.action-archive-url ]]'
out << '    CODIQO_IN_NODE_VERSION: $[[ inputs.node-version ]]'
inputs.each_key do |name|
  envs = mapped[name]
  envs = ["CODIQO_IN_#{name.upcase.tr('-', '_')}"] if envs.empty?
  envs.each { |env| out << "    #{env}: $[[ inputs.#{name} ]]" }
end
out << '  cache:'
out << '    key: codiqo-analyze'
out << '    paths:'
out << '      - .codiqo/cache/'
out << '    when: always'
out << '  script:'
out << '    # a slim JDK image (eclipse-temurin:25-jdk) has no curl to fetch the scripts with; run.sh installs the rest'
out << '    - |'
out << '      if ! command -v curl > /dev/null 2>&1; then'
out << '        if command -v apt-get > /dev/null 2>&1; then'
out << '          apt-get update -qq > /dev/null && apt-get install -y -qq --no-install-recommends curl ca-certificates > /dev/null'
out << '        elif command -v apk > /dev/null 2>&1; then'
out << '          apk add --no-cache curl ca-certificates bash > /dev/null'
out << '        elif command -v microdnf > /dev/null 2>&1; then'
out << '          microdnf install -y curl > /dev/null'
out << '        elif command -v dnf > /dev/null 2>&1; then'
out << '          dnf install -y -q curl > /dev/null'
out << '        fi'
out << '      fi'
out << '    - mkdir -p .codiqo/action'
out << '    - >-'
out << '      curl -fsSL --retry 3 "${CODIQO_ACTION_ARCHIVE_URL:-https://codeload.github.com/codiqo/codiqo-action/tar.gz/${CODIQO_ACTION_REF}}"'
out << '      | tar -xz --strip-components=1 -C .codiqo/action'
out << '    - bash .codiqo/action/scripts/run.sh'
out << '  after_script:'
out << '    - if [ -f .codiqo/action/scripts/run.sh ]; then bash .codiqo/action/scripts/run.sh finish; fi'
out << '  artifacts:'
out << '    name: codiqo-analyze-logs'
out << '    when: always'
out << '    expire_in: $[[ inputs.log-retention-days ]] days'
out << '    paths:'
out << '      - .codiqo/logs/'

puts out.join("\n")
